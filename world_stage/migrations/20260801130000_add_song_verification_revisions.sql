-- Preserve the public stored-function signatures while moving their metadata
-- reads to the latest song revision.
DO $$
DECLARE
    function_definition text;
BEGIN
    FOR function_definition IN
        SELECT pg_get_functiondef(routine.oid)
        FROM pg_proc AS routine
        JOIN pg_namespace AS namespace ON namespace.oid = routine.pronamespace
        WHERE namespace.nspname = 'public'
          AND routine.prokind = 'f'
          AND (
              pg_get_functiondef(routine.oid) LIKE '%FROM song %'
              OR pg_get_functiondef(routine.oid) LIKE '%JOIN song %'
              OR pg_get_functiondef(routine.oid) LIKE E'%FROM song\n%'
              OR pg_get_functiondef(routine.oid) LIKE E'%JOIN song\n%'
          )
    LOOP
        function_definition := replace(
            function_definition,
            E'FROM song\n',
            E'FROM current_song AS song\n'
        );
        function_definition := replace(
            function_definition, 'FROM song ', 'FROM current_song '
        );
        function_definition := replace(
            function_definition,
            'JOIN song ON',
            'JOIN current_song AS song ON'
        );
        function_definition := replace(
            function_definition, 'JOIN song ', 'JOIN current_song '
        );
        EXECUTE function_definition;
    END LOOP;
END;
$$;

