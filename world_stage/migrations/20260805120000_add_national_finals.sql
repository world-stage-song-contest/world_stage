-- Preserve actual historical advancements. The intersection with the target
-- lineup prevents a cached ranking from inventing a qualification that was
-- never applied. The old per-show special quota is used only for this one-time
-- conversion into per-song flags.
INSERT INTO show_qualifier (
    source_show_id, target_show_id, song_id, qualifier_order, is_special
)
WITH boundaries AS (
    SELECT progression.source_show_id, progression.target_show_id,
           progression.priority,
           SUM(progression.qualifier_count) OVER (
               PARTITION BY progression.source_show_id
               ORDER BY progression.priority
           ) AS cutoff,
           COALESCE(source.dtf, 0) AS direct_count,
           COALESCE(source.special, 0) AS special_count
    FROM show_progression AS progression
    JOIN show AS source ON source.id = progression.source_show_id
)
SELECT boundaries.source_show_id, boundaries.target_show_id, results.song_id,
       target_entry.qualifier_order,
       results.place > boundaries.direct_count
       AND results.place <= boundaries.direct_count + boundaries.special_count
FROM boundaries
JOIN country_show_results AS results
  ON results.show_id = boundaries.source_show_id
 AND results.result_mode = 'official'
 AND results.place <= boundaries.cutoff
JOIN song_show AS target_entry
  ON target_entry.show_id = boundaries.target_show_id
 AND target_entry.song_id = results.song_id
ON CONFLICT (target_show_id, song_id) DO NOTHING;

