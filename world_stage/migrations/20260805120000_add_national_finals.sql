CREATE FUNCTION validate_show_progression()
RETURNS trigger AS $$
DECLARE
    source_year bigint;
    source_nf bigint;
    target_year bigint;
    target_nf bigint;
BEGIN
    SELECT year_id, national_final_id INTO source_year, source_nf
    FROM show WHERE id = NEW.source_show_id;
    SELECT year_id, national_final_id INTO target_year, target_nf
    FROM show WHERE id = NEW.target_show_id;

    IF source_year IS DISTINCT FROM target_year
       OR source_nf IS DISTINCT FROM target_nf THEN
        RAISE EXCEPTION 'Progression shows must belong to the same event';
    END IF;

    IF EXISTS (
        WITH RECURSIVE descendants(id) AS (
            SELECT NEW.target_show_id
            UNION
            SELECT progression.target_show_id
            FROM show_progression AS progression
            JOIN descendants ON progression.source_show_id = descendants.id
        )
        SELECT 1 FROM descendants WHERE id = NEW.source_show_id
    ) THEN
        RAISE EXCEPTION 'Show progression cannot contain a cycle';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_show_progression
    BEFORE INSERT OR UPDATE ON show_progression
    FOR EACH ROW EXECUTE FUNCTION validate_show_progression();

