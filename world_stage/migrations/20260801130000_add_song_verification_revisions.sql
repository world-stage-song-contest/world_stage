CREATE FUNCTION trigger_queue_analytics_from_song_data()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    show_id_to_refresh bigint;
BEGIN
    FOR show_id_to_refresh IN
        SELECT show_id FROM song_show WHERE song_id = NEW.song_id
