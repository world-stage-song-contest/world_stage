-- The single source of truth for ballots used in each result mode. Revote
-- results replace an original ballot only when that voter has cast a revote.
CREATE OR REPLACE FUNCTION effective_show_vote_sets(
    p_show_id bigint, p_result_mode text
)
RETURNS SETOF vote_set AS $$
    SELECT vs.*
    FROM vote_set vs
    WHERE vs.show_id = p_show_id
      AND (
          (p_result_mode = 'official' AND vs.result_mode = 'official')
          OR (p_result_mode = 'revote' AND vs.result_mode = 'revote')
          OR (
              p_result_mode = 'revote'
              AND vs.result_mode = 'official'
              AND NOT EXISTS (
                  SELECT 1
                  FROM vote_set replacement
                  WHERE replacement.show_id = vs.show_id
                    AND replacement.voter_id = vs.voter_id
                    AND replacement.result_mode = 'revote'
              )
          )
      );
$$ LANGUAGE sql STABLE;

-- Return the complete rule for one ballot-entry pair. Result rendering,
-- ballot validation, and maximum calculations must consume this function
-- instead of reproducing year or ownership checks independently.
CREATE OR REPLACE FUNCTION ballot_entry_rule(
    p_show_id bigint,
    p_result_mode text,
    p_voter_id bigint,
    p_country_id text,
    p_song_id bigint
)
RETURNS TABLE (
    rule_kind text,
    rule_reason text,
    required_score integer,
    score_cap integer
) AS $$
DECLARE
    v_ruleset text;
    v_revote_ruleset text;
    v_max_score integer;
    v_scored_positions integer;
    v_song_submitter_id bigint;
    v_song_country_id text;
    v_entry_count integer;
    v_owned_entry_count integer;
    v_national_final_id bigint;
    v_allow_owned_entries boolean := false;
BEGIN
    IF p_result_mode NOT IN ('official', 'revote') THEN
        RAISE EXCEPTION 'Unknown result mode: %', p_result_mode;
    END IF;

    SELECT
        sh.voting_ruleset_version,
        sh.revote_ruleset_version,
        MAX(p.score),
        COUNT(p.id),
        sh.national_final_id
    INTO v_ruleset, v_revote_ruleset, v_max_score, v_scored_positions,
         v_national_final_id
    FROM show sh
    JOIN point p ON p.point_system_id = sh.point_system_id
    WHERE sh.id = p_show_id
    GROUP BY sh.voting_ruleset_version, sh.revote_ruleset_version,
             sh.national_final_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Show % does not exist or has no configured points', p_show_id;
    END IF;

    SELECT s.submitter_id, s.country_id
    INTO v_song_submitter_id, v_song_country_id
    FROM song_show ss
    JOIN current_song s ON s.id = ss.song_id
    WHERE ss.show_id = p_show_id
      AND s.id = p_song_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Song % does not belong to show %', p_song_id, p_show_id;
    END IF;

    IF p_result_mode = 'revote' THEN
        IF v_revote_ruleset <> 'v6' THEN
            RAISE EXCEPTION 'Unsupported revote ruleset: %', v_revote_ruleset;
        END IF;

        SELECT
            COUNT(*),
            COUNT(*) FILTER (WHERE s.submitter_id = p_voter_id)
        INTO v_entry_count, v_owned_entry_count
        FROM song_show ss
        JOIN current_song s ON s.id = ss.song_id
        WHERE ss.show_id = p_show_id;

        v_allow_owned_entries :=
            v_entry_count - v_owned_entry_count < v_scored_positions;

        IF NOT v_allow_owned_entries
           AND v_song_submitter_id = p_voter_id THEN
            rule_kind := 'FORBIDDEN';
            rule_reason := 'owner';
            required_score := NULL;
            score_cap := 0;
        ELSE
            rule_kind := 'NORMAL';
            rule_reason := NULL;
            required_score := NULL;
            score_cap := v_max_score;
        END IF;
        RETURN NEXT;
        RETURN;
    END IF;

    -- National finals use a single ordinary ballot. Country affiliation and
    -- ownership of the national final do not restrict voting. A submitter's
    -- own candidates are excluded only when enough other candidates remain to
    -- fill every scoring position, matching the revote capacity exception.
    IF v_national_final_id IS NOT NULL THEN
        SELECT
            COUNT(*),
            COUNT(*) FILTER (WHERE s.submitter_id = p_voter_id)
        INTO v_entry_count, v_owned_entry_count
        FROM song_show ss
        JOIN current_song s ON s.id = ss.song_id
        WHERE ss.show_id = p_show_id;

        v_allow_owned_entries :=
            v_entry_count - v_owned_entry_count < v_scored_positions;

        IF NOT v_allow_owned_entries
           AND v_song_submitter_id = p_voter_id THEN
            rule_kind := 'FORBIDDEN';
            rule_reason := 'owner';
            required_score := NULL;
            score_cap := 0;
        ELSE
            rule_kind := 'NORMAL';
            rule_reason := NULL;
            required_score := NULL;
            score_cap := v_max_score;
        END IF;
        RETURN NEXT;
        RETURN;
    END IF;

    CASE v_ruleset
        WHEN 'v1' THEN
            IF p_country_id = v_song_country_id THEN
                IF NOT EXISTS (
                    SELECT 1
                    FROM show sh
                    JOIN point p ON p.point_system_id = sh.point_system_id
                    WHERE sh.id = p_show_id AND p.score = 1
                ) THEN
                    RAISE EXCEPTION
                        'Voting ruleset v1 requires a 1-point position in show %',
                        p_show_id;
                END IF;
                rule_kind := 'FORCED';
                rule_reason := 'flag';
                required_score := 1;
                score_cap := 1;
            ELSE
                rule_kind := 'NORMAL';
                rule_reason := NULL;
                required_score := NULL;
                score_cap := v_max_score;
            END IF;
        WHEN 'v2' THEN
            IF p_country_id = v_song_country_id THEN
                rule_kind := 'FORBIDDEN';
                rule_reason := 'flag';
                required_score := NULL;
                score_cap := 0;
            ELSE
                rule_kind := 'NORMAL';
                rule_reason := NULL;
                required_score := NULL;
                score_cap := v_max_score;
            END IF;
        WHEN 'v3' THEN
            IF p_country_id = v_song_country_id
               OR v_song_submitter_id = p_voter_id THEN
                rule_kind := 'FORBIDDEN';
                rule_reason := CASE
                    WHEN p_country_id = v_song_country_id
                         AND v_song_submitter_id = p_voter_id
                        THEN 'flag_and_owner'
                    WHEN p_country_id = v_song_country_id THEN 'flag'
                    ELSE 'owner'
                END;
                required_score := NULL;
                score_cap := 0;
            ELSE
                rule_kind := 'NORMAL';
                rule_reason := NULL;
                required_score := NULL;
                score_cap := v_max_score;
            END IF;
        WHEN 'v4', 'v5' THEN
            IF v_song_submitter_id = p_voter_id THEN
                rule_kind := 'FORBIDDEN';
                rule_reason := 'owner';
                required_score := NULL;
                score_cap := 0;
            ELSE
                rule_kind := 'NORMAL';
                rule_reason := NULL;
                required_score := NULL;
                score_cap := v_max_score;
            END IF;
        ELSE
            RAISE EXCEPTION 'Unsupported voting ruleset: %', v_ruleset;
    END CASE;

    RETURN NEXT;
END;
$$ LANGUAGE plpgsql STABLE;

CREATE OR REPLACE FUNCTION voting_ruleset_penalizes_non_voters(
    p_show_id bigint,
    p_result_mode text
)
RETURNS boolean AS $$
    SELECT CASE p_result_mode
        WHEN 'official' THEN official_rules.penalizes_non_voters
        WHEN 'revote' THEN revote_rules.penalizes_non_voters
        ELSE NULL
    END
    FROM show sh
    JOIN voting_ruleset official_rules
      ON official_rules.version = sh.voting_ruleset_version
    JOIN voting_ruleset revote_rules
      ON revote_rules.version = sh.revote_ruleset_version
    WHERE sh.id = p_show_id;
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION calculate_adjusted_points_percentage(
    p_points numeric,
    p_midpoint numeric,
    p_max_possible numeric
)
RETURNS numeric AS $$
BEGIN
    IF p_midpoint IS NULL OR p_midpoint <= 0 THEN
        RETURN 0;
    END IF;
    IF p_points <= p_midpoint THEN
        RETURN 50 * p_points / p_midpoint;
    END IF;
    IF p_max_possible <= p_midpoint THEN
        RAISE EXCEPTION
            'Adjusted maximum % must exceed midpoint % for points %',
            p_max_possible, p_midpoint, p_points;
    END IF;
    RETURN 50 + 50 * (p_points - p_midpoint)
        / (p_max_possible - p_midpoint);
END;
$$ LANGUAGE plpgsql IMMUTABLE;

CREATE OR REPLACE FUNCTION show_progression_status(
    p_show_id bigint, p_place bigint
)
RETURNS text AS $$
    SELECT COALESCE((
        SELECT boundaries.target_short_name
        FROM (
            SELECT target.short_name AS target_short_name,
                   progression.priority,
                   SUM(progression.qualifier_count) OVER (
                       ORDER BY progression.priority
                   ) AS cutoff
            FROM show_progression AS progression
            JOIN show AS target ON target.id = progression.target_show_id
            WHERE progression.source_show_id = p_show_id
        ) AS boundaries
        WHERE p_place <= boundaries.cutoff
        ORDER BY boundaries.priority
        LIMIT 1
    ), 'nq');
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION show_result_progression_status(
    p_show_id bigint,
    p_song_id bigint,
    p_place bigint,
    p_result_mode text
)
RETURNS text AS $$
    SELECT COALESCE(
        CASE WHEN p_result_mode = 'official' THEN (
            SELECT target.short_name
            FROM show_qualifier AS qualifier
            JOIN show AS target ON target.id = qualifier.target_show_id
            WHERE qualifier.source_show_id = p_show_id
              AND qualifier.song_id = p_song_id
        ) END,
        show_progression_status(p_show_id, p_place)
    );
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION show_result_special_qualifier(
    p_show_id bigint,
    p_song_id bigint,
    p_result_mode text
)
RETURNS boolean AS $$
    SELECT p_result_mode = 'official' AND EXISTS (
        SELECT 1 FROM show_qualifier
        WHERE source_show_id = p_show_id
          AND song_id = p_song_id
          AND is_special
    );
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION refresh_show_results_for_mode(
    p_show_id bigint, p_result_mode text
)
RETURNS void AS $$
DECLARE
    v_max_point integer;
    v_system_sum bigint;
    v_inserted integer;
BEGIN
    IF p_result_mode NOT IN ('official', 'revote') THEN
        RAISE EXCEPTION 'Unknown result mode: %', p_result_mode;
    END IF;

    SELECT MAX(p.score), COALESCE(SUM(p.score), 0)
    INTO v_max_point, v_system_sum
    FROM show sh
    JOIN point p ON p.point_system_id = sh.point_system_id
    WHERE sh.id = p_show_id;

    DELETE FROM country_show_results
    WHERE show_id = p_show_id AND result_mode = p_result_mode;

    WITH si AS (
        SELECT
            sh.id, sh.year_id,
            sh.short_name, sh.show_name
        FROM show sh
        WHERE sh.id = p_show_id
    ),
    all_vote_sets AS (
        SELECT * FROM effective_show_vote_sets(p_show_id, p_result_mode)
    ),
    voters_by_country AS (
        SELECT vs.country_id, COUNT(*) AS cnt
        FROM all_vote_sets vs
        WHERE vs.country_id IS NOT NULL
        GROUP BY vs.country_id
    ),
    totals AS (
        SELECT COUNT(*) AS total_valid FROM all_vote_sets
    ),
    point_counts AS (
        SELECT s.id AS song_id, s.country_id, v.score, COUNT(*) AS cnt
        FROM si
        JOIN song_show ss ON ss.show_id = si.id
        JOIN current_song s ON s.id = ss.song_id
        JOIN vote v ON v.song_id = s.id
        JOIN all_vote_sets vs ON vs.id = v.vote_set_id
        JOIN LATERAL ballot_entry_rule(
            si.id, p_result_mode, vs.voter_id, vs.country_id, s.id
        ) rule ON true
        WHERE rule.rule_kind <> 'FORBIDDEN'
          AND (
              rule.rule_kind <> 'FORCED'
              OR v.score = rule.required_score
          )
        GROUP BY s.id, s.country_id, v.score
    ),
    entry_caps AS (
        SELECT s.id AS song_id, SUM(rule.score_cap)::integer AS score_cap
        FROM si
        JOIN song_show ss ON ss.show_id = si.id
        JOIN current_song s ON s.id = ss.song_id
        JOIN country c ON c.id = s.country_id
        CROSS JOIN all_vote_sets vs
        CROSS JOIN LATERAL ballot_entry_rule(
            si.id, p_result_mode, vs.voter_id, vs.country_id, s.id
        ) rule
        WHERE c.is_participating
        GROUP BY s.id
    ),
    aggregated AS (
        SELECT
            s.country_id,
            c.name AS country_name,
            si.id AS show_id,
            s.id AS song_id,
            ss.running_order,
            si.show_name,
            si.short_name,
            si.year_id,
            GREATEST(
                COALESCE(SUM(pc.score * pc.cnt), 0)
                - COALESCE(
                    CASE
                        WHEN NOT voting_ruleset_penalizes_non_voters(
                            si.id, p_result_mode
                        ) THEN 0
                        WHEN p_result_mode = 'revote' THEN ss.revote_penalty
                        ELSE ss.penalty
                    END,
                    0
                ),
                0
            ) AS total_points,
            COALESCE(SUM(pc.cnt), 0) AS total_votes_received,
            COALESCE(
                JSONB_OBJECT_AGG(pc.score::text, pc.cnt ORDER BY pc.score DESC)
                    FILTER (WHERE pc.score IS NOT NULL),
                '{}'::jsonb
            ) AS point_distribution,
            COALESCE(
                STRING_AGG(
                    LPAD(pc.score::text, 3, '0') || ':'
                        || LPAD(pc.cnt::text, 3, '0'),
                    ',' ORDER BY pc.score DESC
                ) FILTER (WHERE pc.score IS NOT NULL),
                ''
            ) AS countback_string,
            (SELECT total_valid FROM totals) AS total_voters,
            COALESCE(ec.score_cap, 0) AS adjusted_max_possible_points_calc,
            CASE
                WHEN v_max_point IS NULL THEN 0
                WHEN si.year_id IS NULL OR si.year_id < 0 OR si.year_id >= 1979
                    THEN v_max_point * (SELECT total_valid FROM totals)
                WHEN (si.year_id BETWEEN 1966 AND 1978)
                     OR (si.year_id = 1965 AND si.short_name = 'f')
                    THEN v_max_point * GREATEST(
                        (SELECT total_valid FROM totals) - COALESCE(vbc.cnt, 0),
                        0
                    )
                WHEN si.year_id = 1960
                    THEN v_max_point * GREATEST(
                        (SELECT total_valid FROM totals) - COALESCE(vbc.cnt, 0),
                        0
                    ) + COALESCE(vbc.cnt, 0)
                ELSE v_max_point * GREATEST(
                    (SELECT total_valid FROM totals) - COALESCE(vbc.cnt, 0),
                    0
                )
            END AS max_possible_points_calc
        FROM si
        JOIN song_show ss ON ss.show_id = si.id
        JOIN current_song s ON s.id = ss.song_id
        JOIN country c ON c.id = s.country_id
        LEFT JOIN point_counts pc ON pc.song_id = s.id
        LEFT JOIN voters_by_country vbc ON vbc.country_id = s.country_id
        LEFT JOIN entry_caps ec ON ec.song_id = s.id
        WHERE c.is_participating
        GROUP BY
            s.country_id, c.name, si.id, s.id, ss.running_order,
            ss.penalty, ss.revote_penalty, si.show_name, si.short_name,
            si.year_id, vbc.cnt, ec.score_cap
    ),
    ranked AS (
        SELECT
            a.*,
            DENSE_RANK() OVER (
                ORDER BY
                    total_points DESC,
                    total_votes_received DESC,
                    countback_string DESC
            ) AS place,
            COUNT(*) OVER () AS total_countries
        FROM aggregated a
    ),
    normalized AS (
        SELECT
            r.*,
            v_system_sum::numeric * r.total_voters
                / NULLIF(r.total_countries, 0) AS points_midpoint_calc
        FROM ranked r
    )
    INSERT INTO country_show_results (
        country_id, country_name, show_id, show_name, short_name, year_id,
        song_id, running_order, total_points, total_votes_received,
        point_distribution, place, total_countries, placement_percentage,
        max_possible_points, points_percentage, adjusted_points_percentage,
        adjusted_max_possible_points, points_midpoint, entry_status,
        special_qualifier, max_pts, total_voters, result_mode
    )
    SELECT
        n.country_id,
        n.country_name,
        n.show_id,
        n.show_name,
        n.short_name,
        n.year_id,
        n.song_id,
        n.running_order,
        n.total_points,
        n.total_votes_received,
        n.point_distribution,
        n.place,
        n.total_countries,
        ROUND(
            CASE
                WHEN n.place = n.total_countries THEN 0
                WHEN n.total_countries > 1
                    THEN ((n.total_countries - n.place)::numeric
                        / (n.total_countries - 1)) * 100
                ELSE 100
            END,
            2
        ),
        COALESCE(n.max_possible_points_calc, 0),
        ROUND(
            COALESCE(
                n.total_points::numeric
                    / NULLIF(n.max_possible_points_calc::numeric, 0),
                0
            ) * 100,
            2
        ),
        ROUND(
            calculate_adjusted_points_percentage(
                n.total_points::numeric,
                n.points_midpoint_calc,
                n.adjusted_max_possible_points_calc::numeric
            ),
            2
        ),
        n.adjusted_max_possible_points_calc,
        ROUND(COALESCE(n.points_midpoint_calc, 0), 6),
        CASE WHEN EXISTS (
            SELECT 1 FROM show_progression
            WHERE source_show_id = n.show_id
        ) THEN show_result_progression_status(
            n.show_id, n.song_id, n.place, p_result_mode
        ) ELSE NULL END,
        show_result_special_qualifier(n.show_id, n.song_id, p_result_mode),
        v_max_point,
        n.total_voters,
        p_result_mode
    FROM normalized n;

    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    RAISE NOTICE 'Refreshed % results for show %; rows=%',
        p_result_mode, p_show_id, v_inserted;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION refresh_show_results(p_show_id bigint)
RETURNS void AS $$
BEGIN
    PERFORM refresh_show_results_for_mode(p_show_id, 'official');
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION refresh_revote_penalties(p_show_id bigint)
RETURNS void AS $$
DECLARE
    max_point integer;
    penalties_enabled boolean;
BEGIN
    SELECT
        MAX(point.score),
        BOOL_OR(rules.penalizes_non_voters)
    INTO max_point, penalties_enabled
    FROM show
    JOIN point ON point.point_system_id = show.point_system_id
    JOIN voting_ruleset rules ON rules.version = show.revote_ruleset_version
    WHERE show.id = p_show_id;

    UPDATE song_show ss
    SET revote_penalty = CASE
        WHEN NOT COALESCE(penalties_enabled, false) THEN 0
        WHEN song.submitter_id IS NULL THEN 0
        WHEN EXISTS (
            SELECT 1
            FROM vote_set
            WHERE show_id = p_show_id
              AND voter_id = song.submitter_id
              AND result_mode = 'official'
        ) THEN 0
        WHEN EXISTS (
            SELECT 1
            FROM vote_set
            WHERE show_id = p_show_id
              AND voter_id = song.submitter_id
              AND result_mode = 'revote'
        ) THEN 0
        ELSE COALESCE(max_point, 0)
    END
    FROM current_song AS song
    WHERE ss.show_id = p_show_id AND song.id = ss.song_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION initialize_revote_penalties_for_show()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.revote_eligible_at IS NOT NULL THEN
        PERFORM refresh_revote_penalties(NEW.id);
        IF EXISTS (
            SELECT 1
            FROM vote_set
            WHERE show_id = NEW.id AND result_mode = 'revote'
        ) THEN
            PERFORM refresh_show_results_for_mode(NEW.id, 'revote');
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION queue_show_result_refresh(
    p_show_id bigint, p_result_mode text
)
RETURNS void AS $$
BEGIN
    IF p_show_id IS NULL OR p_result_mode IS NULL THEN
        RETURN;
    END IF;

    INSERT INTO show_result_refresh_queue (show_id, result_mode)
    VALUES (p_show_id, p_result_mode)
    ON CONFLICT DO NOTHING;

    -- Revote results use official ballots until a voter replaces their ballot.
    IF p_result_mode = 'official' AND EXISTS (
        SELECT 1
        FROM vote_set
        WHERE show_id = p_show_id AND result_mode = 'revote'
    ) THEN
        INSERT INTO show_result_refresh_queue (show_id, result_mode)
        VALUES (p_show_id, 'revote')
        ON CONFLICT DO NOTHING;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION queue_show_result_refresh_from_vote_set_id(
    p_vote_set_id bigint
)
RETURNS void AS $$
DECLARE
    v_show_id bigint;
    v_result_mode text;
BEGIN
    SELECT show_id, result_mode
    INTO v_show_id, v_result_mode
    FROM vote_set
    WHERE id = p_vote_set_id;

    IF FOUND THEN
        PERFORM queue_show_result_refresh(v_show_id, v_result_mode);
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION trigger_queue_show_result_refresh_from_vote()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        PERFORM queue_show_result_refresh_from_vote_set_id(OLD.vote_set_id);
    END IF;

    IF TG_OP <> 'DELETE'
       AND (
           TG_OP <> 'UPDATE'
           OR NEW.vote_set_id IS DISTINCT FROM OLD.vote_set_id
       ) THEN
        PERFORM queue_show_result_refresh_from_vote_set_id(NEW.vote_set_id);
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION trigger_queue_show_result_refresh_from_vote_set()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        PERFORM queue_show_result_refresh(OLD.show_id, OLD.result_mode);
    END IF;

    IF TG_OP <> 'DELETE'
       AND (
           TG_OP <> 'UPDATE'
           OR NEW.show_id IS DISTINCT FROM OLD.show_id
           OR NEW.result_mode IS DISTINCT FROM OLD.result_mode
       ) THEN
        PERFORM queue_show_result_refresh(NEW.show_id, NEW.result_mode);
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION process_show_result_refresh_queue()
RETURNS TRIGGER AS $$
BEGIN
    -- A deferred refresh can outlive the show or its point configuration
    -- when either is removed later in the same transaction.
    IF NOT EXISTS (
        SELECT 1
        FROM show
        JOIN point ON point.point_system_id = show.point_system_id
        WHERE show.id = NEW.show_id
    ) THEN
        DELETE FROM country_show_results
        WHERE show_id = NEW.show_id AND result_mode = NEW.result_mode;
        DELETE FROM show_result_refresh_queue
        WHERE show_id = NEW.show_id AND result_mode = NEW.result_mode;
        RETURN NEW;
    END IF;

    IF NEW.result_mode = 'revote' THEN
        PERFORM refresh_revote_penalties(NEW.show_id);
    END IF;

    PERFORM refresh_show_results_for_mode(NEW.show_id, NEW.result_mode);

    DELETE FROM show_result_refresh_queue
    WHERE show_id = NEW.show_id AND result_mode = NEW.result_mode;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION trigger_queue_show_result_refresh_from_song_show()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        -- Derived rows use restrictive foreign keys. Remove stale results now
        -- so the song or show can be deleted in the same transaction.
        IF TG_OP = 'DELETE'
           OR NEW.song_id IS DISTINCT FROM OLD.song_id
           OR NEW.show_id IS DISTINCT FROM OLD.show_id THEN
            DELETE FROM country_show_results
            WHERE song_id = OLD.song_id AND show_id = OLD.show_id;
        END IF;
        PERFORM queue_show_result_refresh(OLD.show_id, 'official');
    END IF;

    IF TG_OP <> 'DELETE'
       AND (
           TG_OP <> 'UPDATE'
           OR NEW.show_id IS DISTINCT FROM OLD.show_id
       ) THEN
        PERFORM queue_show_result_refresh(NEW.show_id, 'official');
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

-- Rank a year from the explicit progression graph. Terminal shows are tier 1;
-- each step away from a terminal show adds a tier. An entry is ranked from the
-- deepest show it reached, without relying on show names or types.
CREATE OR REPLACE FUNCTION refresh_year_results(p_year_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    DELETE FROM country_year_results WHERE year_id = p_year_id;

    WITH RECURSIVE paths(source_show_id, target_show_id, distance) AS (
        SELECT source_show_id, target_show_id, 1
        FROM show_progression
        UNION ALL
        SELECT paths.source_show_id, progression.target_show_id, paths.distance + 1
        FROM paths
        JOIN show_progression AS progression
          ON progression.source_show_id = paths.target_show_id
    ),
    show_tiers AS (
        SELECT show.id AS show_id, COALESCE(MAX(paths.distance), 0) + 1 AS tier
        FROM show
        LEFT JOIN paths ON paths.source_show_id = show.id
        WHERE show.year_id = p_year_id AND show.national_final_id IS NULL
        GROUP BY show.id
    ),
    candidates AS (
        SELECT csr.*, show_tiers.tier,
               ROW_NUMBER() OVER (
                   PARTITION BY csr.song_id
                   ORDER BY show_tiers.tier, csr.place, csr.show_id
               ) AS reached_order,
               STRING_AGG(
                   LPAD(points.key, 3, '0') || ':' || LPAD(points.value, 3, '0'),
                   ',' ORDER BY points.key::integer DESC
               ) AS countback
        FROM country_show_results AS csr
        JOIN show_tiers ON show_tiers.show_id = csr.show_id
        LEFT JOIN LATERAL jsonb_each_text(csr.point_distribution) AS points ON true
        WHERE csr.year_id = p_year_id AND csr.result_mode = 'official'
        GROUP BY csr.country_id, csr.country_name, csr.show_id, csr.song_id,
                 csr.running_order, csr.show_name, csr.short_name, csr.year_id,
                 csr.total_points, csr.total_votes_received, csr.point_distribution,
                 csr.place, csr.total_countries, csr.placement_percentage,
                 csr.max_possible_points, csr.points_percentage, csr.entry_status,
                 csr.max_pts, csr.total_voters, csr.result_mode,
                 csr.adjusted_points_percentage, csr.adjusted_max_possible_points,
                 csr.points_midpoint, csr.calculated_at, show_tiers.tier
    ),
    reached AS (
        SELECT * FROM candidates WHERE reached_order = 1
    ),
    all_ranked AS (
        SELECT country_id, country_name, year_id, song_id,
               ROW_NUMBER() OVER (
                   ORDER BY tier, points_percentage DESC, total_voters DESC,
                            countback DESC NULLS LAST,
                            running_order NULLS LAST, show_id, song_id
               )::integer AS place
        FROM reached
    ),
    totals AS (
    SELECT COUNT(*) AS total_countries FROM all_ranked
    )
    INSERT INTO country_year_results
    (country_id, country_name, year_id, song_id,
    place, total_countries, placement_percentage)
    SELECT
    ar.country_id,
    ar.country_name,
    ar.year_id,
    ar.song_id,
    ar.place,
    t.total_countries,
    CASE
    WHEN t.total_countries = 1 THEN 100
    ELSE ROUND(
    ((t.total_countries - ar.place)::numeric
    / (t.total_countries - 1)::numeric) * 100,
    3)
    END AS placement_percentage
    FROM all_ranked ar
    CROSS JOIN totals t
    ORDER BY ar.place;
END;
$$;

CREATE OR REPLACE FUNCTION compute_country_year_results()
RETURNS trigger AS $func$
BEGIN
    IF NEW.status = 'closed' AND OLD.status IS DISTINCT FROM 'closed' THEN
    PERFORM refresh_year_results(NEW.id);
    END IF;
    RETURN NEW;
END;
$func$ LANGUAGE plpgsql;

-- Bias-page queries as set-returning SQL functions (per-show measure).
-- See migration 20260701120000_bias_per_show_rewrite.sql for the full rationale.

-- ── Shared scalar helpers ────────────────────────────────────────────

CREATE OR REPLACE FUNCTION bias_logratio(a numeric, e numeric) RETURNS numeric
    IMMUTABLE LANGUAGE sql AS $$ SELECT ln((a + 2) / (e + 2)) $$;

CREATE OR REPLACE FUNCTION bias_z(a numeric, e numeric) RETURNS numeric
    IMMUTABLE LANGUAGE sql AS $$ SELECT CASE WHEN e > 0 THEN (a - e) / sqrt(e) ELSE 0 END $$;

-- Weighted z-score: deviation over the weighted standard deviation.
CREATE OR REPLACE FUNCTION bias_zw(a numeric, e numeric, var numeric) RETURNS numeric
    IMMUTABLE LANGUAGE sql AS $$ SELECT CASE WHEN var > 0 THEN (a - e) / sqrt(var) ELSE 0 END $$;

CREATE OR REPLACE FUNCTION bias_ratio(a numeric, e numeric) RETURNS numeric
    IMMUTABLE LANGUAGE sql AS $$ SELECT CASE WHEN e > 0 THEN a / e - 1 ELSE 0 END $$;

-- effect size (field-weighted log_ratio) + exposure gate (parts, raw E)
CREATE OR REPLACE FUNCTION bias_class(parts bigint, a numeric, e numeric, e_raw numeric) RETURNS text
    IMMUTABLE LANGUAGE sql AS $$
    SELECT CASE
        WHEN parts < 5 OR e_raw < 10 THEN 'inconclusive'
        WHEN abs(bias_logratio(a, e)) < 0.18 THEN 'neutral'
        WHEN bias_logratio(a, e) >= 0.51 THEN 'very-positive'
        WHEN bias_logratio(a, e) <= -0.51 THEN 'very-negative'
        WHEN bias_logratio(a, e) > 0 THEN 'positive'
        ELSE 'negative'
    END
    $$;

-- Reciprocal class keeps the simple ratio bucketing (you-to-them vs them-to-you):
-- ``val`` is user_given/target_to_user - 1; inconclusive when thin or one-sided.
CREATE OR REPLACE FUNCTION bias_reciprocal_class(parts bigint, mutual numeric, val numeric)
    RETURNS text IMMUTABLE LANGUAGE sql AS $$
    SELECT CASE
        WHEN parts < 5 OR mutual IS NULL OR mutual = 0 THEN 'inconclusive'
        WHEN val < -0.5 THEN 'very-negative'
        WHEN val < -0.1 THEN 'negative'
        WHEN val < 0.1 THEN 'neutral'
        WHEN val < 0.5 THEN 'positive'
        ELSE 'very-positive'
    END
    $$;

-- ── Forward: for one voter, which countries are they biased toward? ──

-- The bias views normally use the original ballot.  When requested, a
-- revote replaces that voter’s original ballot for the same show.
CREATE FUNCTION bias_vote_sets(p_include_revotes boolean DEFAULT false)
RETURNS SETOF vote_set
LANGUAGE sql STABLE AS $$
    SELECT DISTINCT ON (vs.show_id, vs.voter_id) vs.*
    FROM vote_set vs
    WHERE vs.result_mode = 'official'
       OR (p_include_revotes AND vs.result_mode = 'revote')
    ORDER BY vs.show_id, vs.voter_id, (vs.result_mode = 'revote') DESC
$$;

CREATE FUNCTION user_country_bias(
    p_user_id bigint,
    p_year_from bigint DEFAULT NULL,
    p_year_to bigint DEFAULT NULL,
    p_include_revotes boolean DEFAULT false
)
RETURNS TABLE (
    country_id text,
    country_name text,
    parts bigint,
    votings_nonblank bigint,
    votings_max bigint,
    given bigint,
    expected numeric,
    bias numeric,
    log_ratio numeric,
    z numeric,
    bias_class text
)
LANGUAGE sql STABLE AS $$
WITH point_max AS (
    SELECT point_system_id, MAX(score) AS max_score FROM point GROUP BY point_system_id
),
user_shows AS (
    SELECT s.id AS show_id
    FROM bias_vote_sets(p_include_revotes) vs
    JOIN show s ON s.id = vs.show_id
    WHERE vs.voter_id = p_user_id
      AND s.status = 'full'
      AND s.year_id > 0
      AND (p_year_from IS NULL OR s.year_id >= p_year_from)
      AND (p_year_to IS NULL OR s.year_id <= p_year_to)
    GROUP BY s.id
),
sc AS (
    SELECT us.show_id, sg.country_id,
        COALESCE(SUM(v.score) FILTER (WHERE vs.voter_id = p_user_id), 0) AS actual,
        COALESCE(SUM(v.score) FILTER (WHERE vs.voter_id <> p_user_id), 0) AS others_t
    FROM user_shows us
    JOIN bias_vote_sets(p_include_revotes) vs ON vs.show_id = us.show_id
    JOIN vote v ON v.vote_set_id = vs.id
    JOIN current_song sg ON sg.id = v.song_id
    WHERE sg.submitter_id <> p_user_id
    GROUP BY us.show_id, sg.country_id
),
pool AS (
    SELECT show_id, SUM(actual) AS pool_v, SUM(others_t) AS others_all
    FROM sc GROUP BY show_id
),
vfield AS (
    SELECT us.show_id, COUNT(DISTINCT sg.id) AS n
    FROM user_shows us
    JOIN song_show ss ON ss.show_id = us.show_id
    JOIN current_song sg ON sg.id = ss.song_id
    WHERE sg.submitter_id <> p_user_id
    GROUP BY us.show_id
),
agg AS (
    SELECT sc.country_id,
        SUM(sc.actual) AS a_raw,
        SUM(sc.others_t::numeric / NULLIF(p.others_all, 0) * p.pool_v) AS e_raw,
        SUM(f.n * sc.actual::numeric / NULLIF(p.pool_v, 0)) AS a_w,
        SUM(f.n * sc.others_t::numeric / NULLIF(p.others_all, 0)) AS e_w,
        SUM(f.n * f.n * sc.others_t::numeric / (NULLIF(p.others_all, 0) * NULLIF(p.pool_v, 0))) AS v_w
    FROM sc
    JOIN pool p ON p.show_id = sc.show_id
    JOIN vfield f ON f.show_id = sc.show_id
    WHERE p.pool_v > 0
    GROUP BY sc.country_id
),
parts AS (
    SELECT sg.country_id,
        COUNT(*) AS parts,
        COUNT(uv.id) AS votings_nonblank,
        COUNT(*) FILTER (WHERE uv.score = pm.max_score) AS votings_max
    FROM user_shows us
    JOIN song_show ss ON ss.show_id = us.show_id
    JOIN current_song sg ON sg.id = ss.song_id
    JOIN show sh ON sh.id = us.show_id
    JOIN point_max pm ON pm.point_system_id = sh.point_system_id
    LEFT JOIN bias_vote_sets(p_include_revotes) uvs ON uvs.show_id = us.show_id AND uvs.voter_id = p_user_id
    LEFT JOIN vote uv ON uv.vote_set_id = uvs.id AND uv.song_id = sg.id
    WHERE sg.submitter_id <> p_user_id
    GROUP BY sg.country_id
)
SELECT pt.country_id,
    c.name AS country_name,
    pt.parts, pt.votings_nonblank, pt.votings_max,
    COALESCE(ag.a_raw, 0)::bigint AS given,
    round(COALESCE(ag.e_raw, 0), 2) AS expected,
    round(bias_ratio(COALESCE(ag.a_raw, 0), COALESCE(ag.e_raw, 0)), 4) AS bias,
    round(bias_logratio(COALESCE(ag.a_w, 0), COALESCE(ag.e_w, 0)), 4) AS log_ratio,
    round(bias_zw(COALESCE(ag.a_w, 0), COALESCE(ag.e_w, 0), COALESCE(ag.v_w, 0)), 3) AS z,
    bias_class(pt.parts, COALESCE(ag.a_w, 0), COALESCE(ag.e_w, 0), COALESCE(ag.e_raw, 0)) AS bias_class
FROM parts pt
LEFT JOIN agg ag ON ag.country_id = pt.country_id
LEFT JOIN country c ON c.id = pt.country_id
ORDER BY bias_logratio(COALESCE(ag.a_w, 0), COALESCE(ag.e_w, 0)) DESC, pt.parts DESC
$$;

