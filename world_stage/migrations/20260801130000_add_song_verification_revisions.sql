-- Rebuild immutable metadata history from the legacy audit stream. The old
-- trigger could emit several audit rows for a single UPDATE, so replay them
-- in audit-id order to retain each visible event as its own revision.
-- BEGIN LEGACY SONG AUDIT RECONSTRUCTION
CREATE FUNCTION insert_reconstructed_song_data(
    state jsonb,
    stable_song_id bigint,
    stable_entry_number integer,
    revision_at timestamptz,
    revision_by bigint,
    is_deletion boolean DEFAULT false
)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF is_deletion THEN
        INSERT INTO song_data (
            song_id, country_id, year_id, entry_number,
            created_at, modified_at, changed_by
        ) VALUES (
            NULL, state ->> 'country_id', (state ->> 'year_id')::bigint,
            stable_entry_number, revision_at, NULL, revision_by
        );
        RETURN;
    END IF;

    INSERT INTO song_data (
        song_id, country_id, year_id, entry_number, language_set_id,
        submitter_id, title, artist, created_at, modified_at, native_title,
        translated_lyrics, romanized_lyrics, native_lyrics, video_link,
        snippet_start, snippet_end, snippet2_start, snippet2_end,
        title_language_id, native_language_id, notes,
        sources, changed_by, poster_link, vtt_link, duration
    ) VALUES (
        stable_song_id, state ->> 'country_id',
        (state ->> 'year_id')::bigint, stable_entry_number,
        (state ->> 'language_set_id')::bigint,
        (state ->> 'submitter_id')::bigint,
        state ->> 'title', state ->> 'artist', revision_at, revision_at,
        state ->> 'native_title', state ->> 'translated_lyrics',
        state ->> 'romanized_lyrics', state ->> 'native_lyrics',
        state ->> 'video_link', (state ->> 'snippet_start')::integer,
        (state ->> 'snippet_end')::integer,
        (state ->> 'snippet2_start')::integer,
        (state ->> 'snippet2_end')::integer,
        (state ->> 'title_language_id')::bigint,
        (state ->> 'native_language_id')::bigint,
        state ->> 'notes', state ->> 'sources', revision_by,
        state ->> 'poster_link', state ->> 'vtt_link',
        (state ->> 'duration')::double precision
    );
END;
$$;

DO $$
DECLARE
    legacy record;
    revision record;
    audit record;
    changed_field record;
    seed song_data%ROWTYPE;
    latest_audit record;
    first_audit_at timestamptz;
    state jsonb;
    stable_song_id bigint;
    stable_entry_number integer;
    has_seed boolean;
    has_create boolean;
    revision_by bigint;
    is_deletion boolean;
    has_data_change boolean;
BEGIN
    FOR legacy IN
        SELECT DISTINCT song_id
        FROM song_audit_log
        WHERE song_id IS NOT NULL
        ORDER BY song_id
    LOOP
        SELECT * INTO seed
        FROM song_data
        WHERE song_id = legacy.song_id
        ORDER BY created_at DESC, id DESC
        LIMIT 1;
        has_seed := FOUND;

        SELECT * INTO latest_audit
        FROM song_audit_log
        WHERE song_id = legacy.song_id
        ORDER BY changed_at DESC, id DESC
        LIMIT 1;

        IF has_seed THEN
            state := TO_JSONB(seed);
            stable_song_id := seed.song_id;
            stable_entry_number := seed.entry_number;
        ELSE
            state := JSONB_BUILD_OBJECT(
                'song_id', NULL,
                'country_id', latest_audit.song_country_id,
                'year_id', latest_audit.song_year_id,
                'entry_number', 1,
                'title', latest_audit.song_title,
                'artist', latest_audit.song_artist
            );
            stable_song_id := NULL;
            stable_entry_number := 1;
        END IF;

        -- Walk backwards to recover the state before the first logged event.
        FOR audit IN
            SELECT *
            FROM song_audit_log
            WHERE song_id = legacy.song_id
            ORDER BY changed_at DESC, id DESC
        LOOP
            FOR changed_field IN
                SELECT field.key, field.value
                FROM JSONB_EACH(COALESCE(audit.changed_fields, '{}'::jsonb)) AS field
                WHERE field.key = ANY (ARRAY[
                    'language_set_id', 'submitter_id', 'title', 'artist',
                    'native_title', 'translated_lyrics', 'romanized_lyrics',
                    'native_lyrics', 'video_link', 'snippet_start',
                    'snippet_end', 'snippet2_start', 'snippet2_end',
                    'title_language_id',
                    'native_language_id', 'notes', 'sources', 'poster_link',
                    'vtt_link', 'duration', 'country_id', 'year_id'
                ])
            LOOP
                state := JSONB_SET(
                    state,
                    ARRAY[changed_field.key],
                    COALESCE(changed_field.value -> 'old', 'null'::jsonb),
                    true
                );
            END LOOP;
        END LOOP;

        SELECT MIN(changed_at), BOOL_OR(event_type = 'create')
        INTO first_audit_at, has_create
        FROM song_audit_log
        WHERE song_id = legacy.song_id;

        IF has_seed THEN
            DELETE FROM song_data WHERE id = seed.id;
        END IF;

        -- Songs predating the audit trigger need a baseline revision before
        -- their first recorded change.
        IF NOT has_create THEN
            PERFORM insert_reconstructed_song_data(
                state,
                stable_song_id,
                stable_entry_number,
                CASE WHEN has_seed THEN LEAST(seed.created_at, first_audit_at)
                     ELSE first_audit_at - INTERVAL '1 microsecond' END,
                NULL
            );
        END IF;

        -- Replay the audit stream forwards. Rows sharing a timestamp came
        -- from one legacy UPDATE and become one immutable revision.
        FOR revision IN
            SELECT DISTINCT changed_at
            FROM song_audit_log
            WHERE song_id = legacy.song_id
            ORDER BY changed_at
        LOOP
            revision_by := NULL;
            is_deletion := false;
            has_data_change := false;

            FOR audit IN
                SELECT *
                FROM song_audit_log
                WHERE song_id = legacy.song_id
                  AND changed_at = revision.changed_at
                ORDER BY id
            LOOP
                revision_by := COALESCE(revision_by, audit.changed_by);
                is_deletion := is_deletion OR audit.event_type = 'delete';
                has_data_change := has_data_change
                    OR audit.event_type NOT IN ('placeholder_on', 'placeholder_off');

                FOR changed_field IN
                    SELECT field.key, field.value
                    FROM JSONB_EACH(
                        COALESCE(audit.changed_fields, '{}'::jsonb)
                    ) AS field
                    WHERE field.key = ANY (ARRAY[
                        'language_set_id', 'submitter_id', 'title', 'artist',
                        'native_title', 'translated_lyrics',
                        'romanized_lyrics', 'native_lyrics', 'video_link',
                        'snippet_start', 'snippet_end', 'snippet2_start',
                        'snippet2_end',
                        'title_language_id', 'native_language_id', 'notes',
                        'sources', 'poster_link', 'vtt_link', 'duration',
                        'country_id', 'year_id'
                    ])
                LOOP
                    state := JSONB_SET(
                        state,
                        ARRAY[changed_field.key],
                        COALESCE(changed_field.value -> 'new', 'null'::jsonb),
                        true
                    );
                END LOOP;
                state := JSONB_SET(
                    JSONB_SET(
                        JSONB_SET(
                            JSONB_SET(
                                state, '{title}',
                                COALESCE(
                                    TO_JSONB(audit.song_title), 'null'::jsonb
                                ), true
                            ),
                            '{artist}',
                            COALESCE(
                                TO_JSONB(audit.song_artist), 'null'::jsonb
                            ), true
                        ),
                        '{country_id}',
                        COALESCE(
                            TO_JSONB(audit.song_country_id), 'null'::jsonb
                        ), true
                    ),
                    '{year_id}',
                    COALESCE(TO_JSONB(audit.song_year_id), 'null'::jsonb), true
                );
            END LOOP;

            IF has_data_change THEN
                PERFORM insert_reconstructed_song_data(
                    state, stable_song_id, stable_entry_number,
                    revision.changed_at, revision_by, is_deletion
                );
            END IF;
        END LOOP;
    END LOOP;
END;
$$;

