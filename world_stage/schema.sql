-- Explicit directed progression graph. Keeping the relationship relational
-- gives both ends real foreign keys; priority defines which block of the
-- source show's ranking advances first when it has multiple destinations.
CREATE TABLE IF NOT EXISTS show_progression (
    source_show_id bigint NOT NULL
        REFERENCES show (id) ON UPDATE RESTRICT ON DELETE CASCADE,
    target_show_id bigint NOT NULL
        REFERENCES show (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    qualifier_count smallint NOT NULL CHECK (qualifier_count > 0),
    priority smallint NOT NULL CHECK (priority > 0),
    PRIMARY KEY (source_show_id, target_show_id),
    UNIQUE (source_show_id, priority),
    CHECK (source_show_id <> target_show_id)
);

CREATE INDEX IF NOT EXISTS show_progression_target_idx
    ON show_progression (target_show_id);

CREATE OR REPLACE FUNCTION validate_show_progression()
RETURNS trigger AS $$
DECLARE
    source_year bigint;
    source_nf bigint;
    target_year bigint;
    target_nf bigint;
BEGIN
    SELECT year_id, national_final_id INTO source_year, source_nf
    FROM show WHERE id = NEW.source_show_id;
    SELECT year_id, national_final_id INTO target_year, target_nf
    FROM show WHERE id = NEW.target_show_id;

    IF source_year IS DISTINCT FROM target_year
       OR source_nf IS DISTINCT FROM target_nf THEN
        RAISE EXCEPTION 'Progression shows must belong to the same event';
    END IF;

    IF EXISTS (
        WITH RECURSIVE descendants(id) AS (
            SELECT NEW.target_show_id
            UNION
            SELECT progression.target_show_id
            FROM show_progression AS progression
            JOIN descendants ON progression.source_show_id = descendants.id
        )
        SELECT 1 FROM descendants WHERE id = NEW.source_show_id
    ) THEN
        RAISE EXCEPTION 'Show progression cannot contain a cycle';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validate_show_progression ON show_progression;
CREATE TRIGGER trg_validate_show_progression
    BEFORE INSERT OR UPDATE ON show_progression
    FOR EACH ROW EXECUTE FUNCTION validate_show_progression();

CREATE OR REPLACE FUNCTION assign_current_voting_ruleset()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.voting_ruleset_version IS NULL THEN
        SELECT version
        INTO NEW.voting_ruleset_version
        FROM voting_ruleset
        WHERE is_current;

        IF NEW.voting_ruleset_version IS NULL THEN
            RAISE EXCEPTION 'No current voting ruleset is configured';
        END IF;
    END IF;
    IF NEW.revote_ruleset_version IS NULL THEN
        SELECT version
        INTO NEW.revote_ruleset_version
        FROM voting_ruleset
        WHERE is_current_revote;

        IF NEW.revote_ruleset_version IS NULL THEN
            RAISE EXCEPTION 'No current revote ruleset is configured';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

