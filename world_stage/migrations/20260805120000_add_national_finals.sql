CREATE FUNCTION ballot_entry_rule(
    p_show_id bigint,
    p_result_mode text,
    p_voter_id bigint,
    p_country_id text,
    p_song_id bigint
)
RETURNS TABLE (
    rule_kind text,
    rule_reason text,
    required_score integer,
    score_cap integer
) AS $$
DECLARE
    v_national_final_id bigint;
    v_max_score integer;
    v_scored_positions integer;
    v_song_submitter_id bigint;
    v_entry_count integer;
    v_owned_entry_count integer;
BEGIN
    SELECT show.national_final_id, MAX(point.score), COUNT(point.id)
    INTO v_national_final_id, v_max_score, v_scored_positions
    FROM show
    JOIN point ON point.point_system_id = show.point_system_id
    WHERE show.id = p_show_id
    GROUP BY show.national_final_id;

    IF v_national_final_id IS NULL THEN
        RETURN QUERY
        SELECT contest.rule_kind, contest.rule_reason,
               contest.required_score, contest.score_cap
        FROM contest_ballot_entry_rule(
            p_show_id, p_result_mode, p_voter_id, p_country_id, p_song_id
        ) AS contest;
        RETURN;
    END IF;

    IF p_result_mode NOT IN ('official', 'revote') THEN
        RAISE EXCEPTION 'Unknown result mode: %', p_result_mode;
    END IF;

    SELECT song.submitter_id
    INTO v_song_submitter_id
    FROM song_show
    JOIN current_song AS song ON song.id = song_show.song_id
    WHERE song_show.show_id = p_show_id AND song.id = p_song_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Song % does not belong to show %', p_song_id, p_show_id;
    END IF;

    SELECT COUNT(*), COUNT(*) FILTER (WHERE song.submitter_id = p_voter_id)
    INTO v_entry_count, v_owned_entry_count
    FROM song_show
    JOIN current_song AS song ON song.id = song_show.song_id
    WHERE song_show.show_id = p_show_id;

    IF v_entry_count - v_owned_entry_count >= v_scored_positions
       AND v_song_submitter_id = p_voter_id THEN
        rule_kind := 'FORBIDDEN';
        rule_reason := 'owner';
        required_score := NULL;
        score_cap := 0;
    ELSE
        rule_kind := 'NORMAL';
        rule_reason := NULL;
        required_score := NULL;
        score_cap := v_max_score;
    END IF;
    RETURN NEXT;
END;
$$ LANGUAGE plpgsql STABLE;

