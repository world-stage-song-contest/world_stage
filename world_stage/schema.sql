-- Resolve the browser MIME type for media URLs that the radio can play
-- directly. Query strings and fragments do not affect the file extension.
CREATE OR REPLACE FUNCTION radio_media_type(p_url text)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE
AS $$
    SELECT CASE lower(
        substring(
            split_part(split_part(p_url, '#', 1), '?', 1)
            FROM '\.([^.]+)$'
        )
    )
        WHEN 'mp4' THEN 'video/mp4'
        WHEN 'm4v' THEN 'video/mp4'
        WHEN 'm4a' THEN 'audio/mp4'
        WHEN 'webm' THEN 'video/webm'
        WHEN 'ogg' THEN 'video/ogg'
        -- These files contain H.264/AAC media that browsers accept when
        -- advertised as MP4 rather than video/quicktime.
        WHEN 'mov' THEN 'video/mp4'
        ELSE NULL
    END
$$;

-- The radio schedule is also its immutable play history. Song metadata is
-- copied into each row intentionally: later catalogue edits or deletion must
-- not rewrite what the station had scheduled.
CREATE TABLE IF NOT EXISTS radio_slot (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    source_song_id bigint NOT NULL,
    title text,
    artist text,
    media_url text NOT NULL,
    media_type text NOT NULL,
    media_duration_seconds double precision NOT NULL,
    poster_url text,
    vtt_url text,
    country_code text NOT NULL,
    country_name text NOT NULL,
    year_id bigint NOT NULL,
    year_label text NOT NULL,
    pool_size_at_queue integer NOT NULL,
    queued_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    play_window tstzrange GENERATED ALWAYS AS (
        tstzrange(starts_at, ends_at, '[)')
    ) STORED,
    CONSTRAINT radio_slot_time_order CHECK (ends_at > starts_at),
    CONSTRAINT radio_slot_duration_positive CHECK (media_duration_seconds > 0),
    CONSTRAINT radio_slot_pool_size_positive CHECK (pool_size_at_queue > 0),
    CONSTRAINT radio_slot_no_overlap EXCLUDE USING gist (play_window WITH &&)
);

