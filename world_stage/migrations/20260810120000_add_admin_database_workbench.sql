CREATE TABLE admin_saved_query (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    description text NOT NULL DEFAULT '',
    query_kind text NOT NULL CHECK (query_kind IN ('builder', 'sql')),
    operation text NOT NULL CHECK (operation IN ('select', 'insert', 'update')),
    definition jsonb,
    sql_text text,
    parameters jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_by bigint REFERENCES account (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (char_length(name) BETWEEN 1 AND 200),
    CHECK (jsonb_typeof(parameters) = 'array'),
    CHECK (
        (query_kind = 'builder' AND definition IS NOT NULL
            AND jsonb_typeof(definition) = 'object' AND sql_text IS NULL)
        OR
        (query_kind = 'sql' AND sql_text IS NOT NULL AND definition IS NULL)
    )
);

CREATE UNIQUE INDEX admin_saved_query_name_unique
    ON admin_saved_query (LOWER(name));

CREATE TABLE admin_query_log (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    actor_id bigint REFERENCES account (id) ON DELETE SET NULL,
    saved_query_id bigint REFERENCES admin_saved_query (id) ON DELETE SET NULL,
    source text NOT NULL CHECK (source IN ('builder', 'sql', 'stored_builder', 'stored_sql')),
    operation text NOT NULL CHECK (operation IN ('select', 'insert', 'update', 'other')),
    query_text text NOT NULL,
    definition jsonb,
    parameter_schema jsonb NOT NULL DEFAULT '[]'::jsonb,
    referenced_objects text[] NOT NULL DEFAULT '{}',
    result_format text NOT NULL DEFAULT 'screen' CHECK (result_format IN ('screen', 'csv')),
    query_fingerprint text NOT NULL,
    success boolean,
    row_count bigint,
    duration_ms integer,
    sqlstate text,
    error_message text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamptz,
    CHECK (definition IS NULL OR jsonb_typeof(definition) = 'object'),
    CHECK (jsonb_typeof(parameter_schema) = 'array')
);

CREATE INDEX admin_query_log_created_at_idx
    ON admin_query_log (created_at DESC);

CREATE INDEX admin_query_log_fingerprint_idx
    ON admin_query_log (query_fingerprint, created_at DESC);

CREATE INDEX admin_query_log_actor_idx
    ON admin_query_log (actor_id, created_at DESC);
