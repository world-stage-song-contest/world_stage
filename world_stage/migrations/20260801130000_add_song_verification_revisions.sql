WITH initial_state AS (
    SELECT song.id AS song_id,
           data.id AS song_data_id,
           data.created_at,
           CASE WHEN year.status IN ('closed', 'ongoing')
                THEN 'accepted' ELSE 'pending' END AS approval_status,
           COALESCE((
               SELECT CASE audit.event_type
                          WHEN 'placeholder_on' THEN false
                          WHEN 'placeholder_off' THEN true
                      END
               FROM song_audit_log AS audit
               WHERE audit.song_id = song.id
                 AND audit.event_type IN ('placeholder_on', 'placeholder_off')
               ORDER BY audit.changed_at, audit.id
               LIMIT 1
           ), song.is_placeholder, false) AS is_placeholder
    FROM song
    JOIN year ON year.id = song.year_id
    JOIN LATERAL (
        SELECT revision.id, revision.created_at
        FROM song_data AS revision
        WHERE revision.song_id = song.id
        ORDER BY revision.created_at, revision.id
        LIMIT 1
    ) AS data ON true
)
